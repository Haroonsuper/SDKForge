import { SDKFile, SDKGenOptions, SpecValidationDiagnostic } from '../../types/spec';
import { toCamelCase, toPascalCase } from '../parser';
import { apiKeyHeaderName, camelArg, tsKey, clientClassNameFor } from './common';
import { safeText, safePackageName, safeVersion, safeAuthor, DEFAULT_BASE_URL } from '../sanitize';

export function generateTypeScriptSDK(
  spec: SpecValidationDiagnostic,
  opts: SDKGenOptions
): SDKFile[] {
  const files: SDKFile[] = [];

  const pkgName = safePackageName(opts.packageName, 'api-client-sdk');
  const pkgVersion = safeVersion(opts.version);
  const apiKeyHeader = apiKeyHeaderName(spec);
  const schemaNames = new Set(spec.schemas.map(sc => sc.name));
  // Qualify schema names with the Types namespace (client.ts imports types as `Types`)
  const qual = (t: string): string =>
    t.includes('"') ? t : t.replace(/\b[A-Za-z_]\w*\b/g, m => (schemaNames.has(m) ? `Types.${m}` : m));
  const clientClassName = clientClassNameFor(spec);

  // 1. Generate src/types.ts
  let typesContent = `/**
 * ${spec.title} - TypeScript SDK Types
 * Auto-generated by SDKForge Engine
 * Version: ${pkgVersion}
 */

export interface ClientConfig {
  baseUrl?: string;
  apiKey?: string;
  bearerToken?: string;
  headers?: Record<string, string>;
  timeoutMs?: number;
}

export class APIError extends Error {
  public status: number;
  public data: any;

  constructor(message: string, status: number, data?: any) {
    super(message);
    this.name = 'APIError';
    this.status = status;
    this.data = data;
  }
}
\n`;

  // Schemas
  if (spec.schemas.length > 0) {
    typesContent += `// ------------------ Data Models & Schemas ------------------\n\n`;
    for (const schema of spec.schemas) {
      typesContent += `export interface ${schema.name} {\n`;
      for (const prop of schema.properties) {
        const optional = prop.required ? '' : '?';
        const doc = prop.description ? `  /** ${prop.description} */\n` : '';
        typesContent += `${doc}  ${tsKey(prop.name)}${optional}: ${prop.type};\n`;
      }
      typesContent += `}\n\n`;
    }
  }

  // Request & Query Param Interfaces for each endpoint
  typesContent += `// ------------------ Endpoint Request Types ------------------\n\n`;
  for (const ep of spec.endpoints) {
    const queryParams = ep.parameters.filter(p => p.in === 'query');
    if (queryParams.length > 0) {
      const typeName = `${toPascalCase(ep.functionName)}Query`;
      typesContent += `export interface ${typeName} {\n`;
      for (const q of queryParams) {
        const opt = q.required ? '' : '?';
        typesContent += `  ${tsKey(q.name)}${opt}: ${q.type};\n`;
      }
      typesContent += `}\n\n`;
    }

    if (ep.requestBodyProperties && !ep.requestBodySchema) {
      const bodyTypeName = `${toPascalCase(ep.functionName)}Payload`;
      typesContent += `export interface ${bodyTypeName} {\n`;
      for (const prop of ep.requestBodyProperties) {
        const opt = prop.required ? '' : '?';
        typesContent += `  ${tsKey(prop.name)}${opt}: ${prop.type};\n`;
      }
      typesContent += `}\n\n`;
    }
  }

  files.push({
    name: 'types.ts',
    path: 'src/types.ts',
    content: typesContent,
    language: 'typescript',
    sizeBytes: new TextEncoder().encode(typesContent).length
  });

  // 2. Generate src/client.ts
  const isAxios = opts.httpClient === 'axios';
  let clientContent = `/**
 * ${spec.title} - Main SDK Client
 * Auto-generated by SDKForge Engine
 */

import { ClientConfig, APIError } from './types';
import * as Types from './types';
${isAxios ? `import axios, { AxiosInstance } from 'axios';\n` : ''}
export class ${clientClassName} {
  private baseUrl: string;
  private apiKey?: string;
  private bearerToken?: string;
  private defaultHeaders: Record<string, string>;
  private timeoutMs: number;
  ${isAxios ? 'private axiosInstance: AxiosInstance;\n' : ''}
  constructor(config: ClientConfig = {}) {
    this.baseUrl = (config.baseUrl || '${spec.baseUrl || 'https://api.example.com'}').replace(/\\/+$/, '');
    this.apiKey = config.apiKey;
    this.bearerToken = config.bearerToken;
    this.timeoutMs = config.timeoutMs || 30000;
    this.defaultHeaders = {
      'Content-Type': 'application/json',
      'Accept': 'application/json',
      ...(config.headers || {})
    };

    if (this.bearerToken) {
      this.defaultHeaders['Authorization'] = \`Bearer \${this.bearerToken}\`;
    } else if (this.apiKey) {
      this.defaultHeaders['${apiKeyHeader}'] = this.apiKey;
    }
${isAxios ? `
    this.axiosInstance = axios.create({
      baseURL: this.baseUrl,
      headers: this.defaultHeaders,
      timeout: this.timeoutMs,
    });\n` : ''}  }

  /**
   * Internal HTTP execution pipeline
   */
  private async request<T>(
    method: string,
    path: string,
    options: {
      params?: Record<string, any>;
      body?: any;
      headers?: Record<string, string>;
    } = {}
  ): Promise<T> {
${isAxios ? `    try {
      const response = await this.axiosInstance.request<T>({
        method,
        url: path,
        params: options.params,
        data: options.body,
        headers: options.headers,
      });
      return response.data;
    } catch (error: any) {
      if (error.response) {
        throw new APIError(error.response.data?.message || error.message, error.response.status, error.response.data);
      }
      throw new APIError(error.message, 0);
    }` : `    const url = new URL(this.baseUrl + path);
    if (options.params) {
      Object.entries(options.params).forEach(([key, value]) => {
        if (value !== undefined && value !== null) {
          url.searchParams.append(key, String(value));
        }
      });
    }

    const headers: Record<string, string> = {
      ...this.defaultHeaders,
      ...(options.headers || {})
    };

    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), this.timeoutMs);

    try {
      const response = await fetch(url.toString(), {
        method,
        headers,
        body: options.body ? JSON.stringify(options.body) : undefined,
        signal: controller.signal
      });

      clearTimeout(timer);

      if (!response.ok) {
        let errData;
        try {
          errData = await response.json();
        } catch {
          errData = await response.text();
        }
        throw new APIError(
          \`HTTP error \${response.status}: \${response.statusText}\`,
          response.status,
          errData
        );
      }

      const contentType = response.headers.get('content-type') || '';
      if (contentType.includes('application/json')) {
        return (await response.json()) as T;
      }
      return (await response.text()) as unknown as T;
    } catch (err: any) {
      clearTimeout(timer);
      if (err instanceof APIError) throw err;
      throw new APIError(err.message || 'Network request failed', 0);
    }`}
  }

  // ------------------ API Endpoint Methods ------------------
`;

  // Methods
  for (const ep of spec.endpoints) {
    const pathParams = ep.parameters.filter(p => p.in === 'path');
    const queryParams = ep.parameters.filter(p => p.in === 'query');

    const args: string[] = [];
    for (const p of pathParams) {
      args.push(`${camelArg(p)}: ${p.type}`);
    }

    if (ep.requestBodySchema) {
      args.push(`payload: ${qual(ep.requestBodySchema)}`);
    } else if (ep.requestBodyProperties) {
      args.push(`payload: Types.${toPascalCase(ep.functionName)}Payload`);
    }

    if (queryParams.length > 0) {
      args.push(`query?: Types.${toPascalCase(ep.functionName)}Query`);
    }

    const docStr = safeText(ep.description || ep.summary);
    clientContent += `
  /**
   * ${ep.summary}
   * ${docStr ? `@description ${docStr}\n   * ` : ''}@method ${ep.method} ${ep.path}
   */
  public async ${ep.functionName}(${args.join(', ')}): Promise<${qual(ep.responseType)}> {
    let resolvedPath = '${ep.path}';
${pathParams.map(p => `    resolvedPath = resolvedPath.replace('{${p.name}}', encodeURIComponent(String(${camelArg(p)})));`).join('\n')}

    return this.request<${qual(ep.responseType)}>(
      '${ep.method}',
      resolvedPath,
      {
        params: ${queryParams.length > 0 ? 'query' : 'undefined'},
        body: ${ep.requestBodySchema || ep.requestBodyProperties ? 'payload' : 'undefined'}
      }
    );
  }
`;
  }

  clientContent += `}\n`;

  files.push({
    name: 'client.ts',
    path: 'src/client.ts',
    content: clientContent,
    language: 'typescript',
    sizeBytes: new TextEncoder().encode(clientContent).length
  });

  // 3. Generate src/index.ts
  const indexContent = `/**
 * ${spec.title}
 * Entry point for client and types
 */

export * from './types';
export * from './client';
export { ${clientClassName} as default } from './client';
`;

  files.push({
    name: 'index.ts',
    path: 'src/index.ts',
    content: indexContent,
    language: 'typescript',
    sizeBytes: new TextEncoder().encode(indexContent).length
  });

  // 4. Generate package.json
  const packageJson = {
    name: pkgName,
    version: pkgVersion,
    description: spec.description || `TypeScript SDK for ${spec.title}`,
    main: 'dist/index.js',
    types: 'dist/index.d.ts',
    scripts: {
      build: 'tsc',
      test: 'vitest run'
    },
    author: opts.author || 'API Platform Team',
    license: 'MIT',
    dependencies: isAxios ? { axios: '^1.7.9' } : {},
    devDependencies: {
      typescript: '^5.7.0',
      vitest: '^3.0.5'
    }
  };

  const pkgJsonStr = JSON.stringify(packageJson, null, 2);
  files.push({
    name: 'package.json',
    path: 'package.json',
    content: pkgJsonStr,
    language: 'json',
    sizeBytes: new TextEncoder().encode(pkgJsonStr).length
  });

  // 5. Generate tsconfig.json
  const tsConfig = {
    compilerOptions: {
      target: 'ES2022',
      module: 'CommonJS',
      declaration: true,
      outDir: './dist',
      strict: true,
      esModuleInterop: true,
      skipLibCheck: true,
      forceConsistentCasingInFileNames: true
    },
    include: ['src/**/*']
  };

  files.push({
    name: 'tsconfig.json',
    path: 'tsconfig.json',
    content: JSON.stringify(tsConfig, null, 2),
    language: 'json',
    sizeBytes: new TextEncoder().encode(JSON.stringify(tsConfig)).length
  });

  // 6. Generate README.md
  const sampleEp = spec.endpoints[0];
  let sampleCall = `const result = await client.${sampleEp?.functionName || 'getItems'}();`;
  if (sampleEp && sampleEp.parameters.some(p => p.in === 'path')) {
    const firstParam = sampleEp.parameters.find(p => p.in === 'path')?.name || 'id';
    sampleCall = `const result = await client.${sampleEp.functionName}("sample_${firstParam}_123");`;
  }

  const readmeContent = `# ${spec.title} - TypeScript SDK

${spec.description || 'Production-ready TypeScript client library generated deterministically by SDKForge.'}

## Installation

\`\`\`bash
npm install ${pkgName}
# or
yarn add ${pkgName}
# or
pnpm add ${pkgName}
\`\`\`

## Quickstart

\`\`\`typescript
import { ${clientClassName} } from '${pkgName}';

const client = new ${clientClassName}({
  baseUrl: '${spec.baseUrl || 'https://api.example.com'}',
  bearerToken: process.env.API_BEARER_TOKEN,
  // Or apiKey: process.env.API_KEY,
});

async function main() {
  try {
    ${sampleCall}
    console.log('Result:', result);
  } catch (error) {
    if (error instanceof Error) {
      console.error('API Error:', error.message);
    }
  }
}

main();
\`\`\`

## Features

- **100% Typed**: Strict TypeScript interfaces for all request inputs and response schemas.
- **Lightweight**: Zero external dependencies (uses native fetch) or standard Axios.
- **Error Handling**: Custom \`APIError\` containing HTTP status codes and API error response bodies.
- **Configurable**: Configurable timeouts, custom base URLs, and custom request headers.

## Available Methods (${spec.endpoints.length} Total)

| Method | HTTP | Path | Description |
| :--- | :--- | :--- | :--- |
${spec.endpoints.slice(0, 15).map(ep => `| \`${ep.functionName}\` | \`${ep.method}\` | \`${ep.path}\` | ${ep.summary} |`).join('\n')}

${spec.endpoints.length > 15 ? `*...and ${spec.endpoints.length - 15} more methods.*\n` : ''}

## License

MIT © ${new Date().getFullYear()} ${opts.author || 'API Platform Team'}
`;

  files.push({
    name: 'README.md',
    path: 'README.md',
    content: readmeContent,
    language: 'markdown',
    sizeBytes: new TextEncoder().encode(readmeContent).length
  });

  // 7. Generate tests/client.test.ts
  const testContent = `/**
 * Unit Tests for ${clientClassName}
 */

import { describe, it, expect } from 'vitest';
import { ${clientClassName} } from '../src/client';
import { APIError } from '../src/types';

describe('${clientClassName}', () => {
  it('instantiates client with valid baseUrl', () => {
    const client = new ${clientClassName}({
      baseUrl: '${spec.baseUrl || 'https://api.example.com'}',
      bearerToken: 'test_token_123'
    });

    expect(client).toBeDefined();
    expect(client).toBeInstanceOf(${clientClassName});
  });

  it('exposes APIError with status codes', () => {
    const err = new APIError('Resource not found', 404, { detail: 'Missing ID' });
    expect(err.status).toBe(404);
    expect(err.message).toBe('Resource not found');
    expect(err.data.detail).toBe('Missing ID');
  });
});
`;

  files.push({
    name: 'client.test.ts',
    path: 'tests/client.test.ts',
    content: testContent,
    language: 'typescript',
    sizeBytes: new TextEncoder().encode(testContent).length
  });

  return files;
}
