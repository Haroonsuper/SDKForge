import { SDKFile, SDKGenOptions, SpecValidationDiagnostic } from '../../types/spec';
import { toCamelCase, toPascalCase } from '../parser';
import { apiKeyHeaderName, camelArg, clientClassNameFor } from './common';
import { safeText, safePackageName, safeIdent, safeVarName } from '../sanitize';

function mapGoType(typeStr: string): string {
  if (typeStr.includes('"')) return typeStr.endsWith('[]') ? '[]string' : 'string'; // string-literal unions
  if (typeStr === 'string') return 'string';
  if (typeStr === 'number') return 'float64';
  if (typeStr === 'integer') return 'int64';
  if (typeStr === 'boolean') return 'bool';
  if (typeStr.endsWith('[]')) {
    const item = typeStr.slice(0, -2);
    return `[]${mapGoType(item)}`;
  }
  if (typeStr === 'Record<string, any>' || typeStr === 'any') return 'map[string]interface{}';
  return `*${typeStr}`;
}

export function generateGoSDK(
  spec: SpecValidationDiagnostic,
  opts: SDKGenOptions
): SDKFile[] {
  const files: SDKFile[] = [];

  let pkgName = safePackageName(opts.packageName, 'apisdk').replace(/[^a-z0-9]/g, '') || 'apisdk';
  if (/^[0-9]/.test(pkgName)) pkgName = `sdk${pkgName}`;
  pkgName = safeVarName(pkgName, 'apisdk');
  const apiKeyHeader = apiKeyHeaderName(spec);
  const clientClassName = clientClassNameFor(spec);

  // 1. Generate models.go
  let modelsContent = `// Package ${pkgName} provides the Go SDK for ${spec.title}.
// Auto-generated by SDKForge Engine.
package ${pkgName}

import (
	"fmt"
)

// APIError represents an HTTP error response from the API.
type APIError struct {
	StatusCode int
	Message    string
	Body       string
}

func (e *APIError) Error() string {
	return fmt.Sprintf("api error (status %d): %s", e.StatusCode, e.Message)
}
\n`;

  for (const schema of spec.schemas) {
    modelsContent += `// ${schema.name} represents ${safeText(schema.description) || 'API data entity'}.\n`;
    modelsContent += `type ${schema.name} struct {\n`;
    const usedFields = new Set<string>();
    for (const p of schema.properties) {
      let goFieldName = safeIdent(toPascalCase(p.name), 'Field');
      goFieldName = goFieldName.charAt(0).toUpperCase() + goFieldName.slice(1);
      if (!/^[A-Z]/.test(goFieldName)) goFieldName = `F${goFieldName}`;
      for (let i = 2; usedFields.has(goFieldName); i++) goFieldName = `${goFieldName.replace(/\d+$/, '')}${i}`;
      usedFields.add(goFieldName);
      const goType = mapGoType(p.type);
      const jsonTag = p.required ? `json:"${p.name}"` : `json:"${p.name},omitempty"`;
      modelsContent += `\t${goFieldName} ${goType} \`${jsonTag}\`\n`;
    }
    modelsContent += `}\n\n`;
  }

  files.push({
    name: 'models.go',
    path: 'models.go',
    content: modelsContent,
    language: 'go',
    sizeBytes: new TextEncoder().encode(modelsContent).length
  });

  // 2. Generate client.go
  let clientContent = `package ${pkgName}

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"strings"
	"time"
)

// ClientOption configures the API Client.
type ClientOption func(*Client)

// Client is the primary API client.
type Client struct {
	baseURL    string
	apiKey     string
	token      string
	httpClient *http.Client
	headers    map[string]string
}

// WithBaseURL overrides the default endpoint URL.
func WithBaseURL(u string) ClientOption {
	return func(c *Client) {
		c.baseURL = strings.TrimRight(u, "/")
	}
}

// WithBearerToken sets authorization bearer token.
func WithBearerToken(token string) ClientOption {
	return func(c *Client) {
		c.token = token
	}
}

// WithAPIKey sets API Key.
func WithAPIKey(key string) ClientOption {
	return func(c *Client) {
		c.apiKey = key
	}
}

// WithHTTPClient provides a custom http.Client.
func WithHTTPClient(hc *http.Client) ClientOption {
	return func(c *Client) {
		c.httpClient = hc
	}
}

// NewClient initializes a new ${clientClassName} client.
func NewClient(opts ...ClientOption) *Client {
	c := &Client{
		baseURL: "${spec.baseUrl || 'https://api.example.com'}",
		httpClient: &http.Client{
			Timeout: 30 * time.Second,
		},
		headers: map[string]string{
			"Content-Type": "application/json",
			"Accept":       "application/json",
			"User-Agent":   "${pkgName}-go-sdk/v1.0.0",
		},
	}

	for _, opt := range opts {
		opt(c)
	}

	if c.token != "" {
		c.headers["Authorization"] = "Bearer " + c.token
	} else if c.apiKey != "" {
		c.headers["${apiKeyHeader}"] = c.apiKey
	}

	return c
}

func (c *Client) doRequest(ctx context.Context, method, path string, query url.Values, body interface{}, out interface{}) error {
	reqURL := c.baseURL + path
	if len(query) > 0 {
		reqURL += "?" + query.Encode()
	}

	var bodyReader io.Reader
	if body != nil {
		data, err := json.Marshal(body)
		if err != nil {
			return fmt.Errorf("marshal request body: %w", err)
		}
		bodyReader = bytes.NewReader(data)
	}

	req, err := http.NewRequestWithContext(ctx, method, reqURL, bodyReader)
	if err != nil {
		return fmt.Errorf("create request: %w", err)
	}

	for k, v := range c.headers {
		req.Header.Set(k, v)
	}

	resp, err := c.httpClient.Do(req)
	if err != nil {
		return fmt.Errorf("execute request: %w", err)
	}
	defer resp.Body.Close()

	respBytes, err := io.ReadAll(resp.Body)
	if err != nil {
		return fmt.Errorf("read response body: %w", err)
	}

	if resp.StatusCode < 200 || resp.StatusCode >= 300 {
		return &APIError{
			StatusCode: resp.StatusCode,
			Message:    resp.Status,
			Body:       string(respBytes),
		}
	}

	if out != nil && len(respBytes) > 0 {
		if err := json.Unmarshal(respBytes, out); err != nil {
			return fmt.Errorf("unmarshal response: %w", err)
		}
	}

	return nil
}
`;

  files.push({
    name: 'client.go',
    path: 'client.go',
    content: clientContent,
    language: 'go',
    sizeBytes: new TextEncoder().encode(clientContent).length
  });

  // 3. Generate endpoints.go
  const anyPathParams = spec.endpoints.some(e => e.parameters.some(p => p.in === 'path'));
  const goImports = ['context', ...(anyPathParams ? ['fmt'] : []), 'net/url', ...(anyPathParams ? ['strings'] : [])];
  let endpointsContent = `package ${pkgName}

import (
${goImports.map(i => `\t"${i}"`).join('\n')}
)
\n`;

  for (const ep of spec.endpoints) {
    let goMethodName = safeIdent(toPascalCase(ep.functionName), 'Endpoint');
    goMethodName = goMethodName.charAt(0).toUpperCase() + goMethodName.slice(1);
    const pathParams = ep.parameters.filter(p => p.in === 'path');
    const queryParams = ep.parameters.filter(p => p.in === 'query');

    const paramsList: string[] = ['ctx context.Context'];
    for (const p of pathParams) {
      paramsList.push(`${camelArg(p)} ${mapGoType(p.type)}`);
    }

    if (queryParams.length > 0) {
      paramsList.push('query url.Values');
    }

    if (ep.requestBodySchema) {
      paramsList.push(`payload *${ep.requestBodySchema}`);
    } else if (ep.requestBodyProperties) {
      paramsList.push(`payload map[string]interface{}`);
    }

    let returnType = 'error';
    let returnVal = 'nil';
    let returnTypeDoc = 'error';
    if (ep.responseType && ep.responseType !== 'void') {
      const mapped = mapGoType(ep.responseType);
      returnType = `(${mapped}, error)`;
      returnVal = `result, nil`;
      returnTypeDoc = mapped;
    }

    endpointsContent += `// ${goMethodName} executes ${ep.method} ${ep.path}
// ${safeText(ep.summary)}
func (c *Client) ${goMethodName}(${paramsList.join(', ')}) ${returnType} {
	relPath := "${ep.path}"
`;

    for (const p of pathParams) {
      endpointsContent += `\trelPath = strings.ReplaceAll(relPath, "{${p.name}}", url.PathEscape(fmt.Sprint(${camelArg(p)})))\n`;
    }

    if (queryParams.length === 0) {
      endpointsContent += `\tvar query url.Values\n`;
    }

    if (ep.responseType && ep.responseType !== 'void') {
      const rawType = mapGoType(ep.responseType);
      endpointsContent += `\tvar result ${rawType}\n`;
      endpointsContent += `\terr := c.doRequest(ctx, "${ep.method}", relPath, query, ${Boolean(ep.requestBodySchema || ep.requestBodyProperties) ? 'payload' : 'nil'}, &result)\n`;
      endpointsContent += `\tif err != nil {\n\t\tvar zero ${rawType}\n\t\treturn zero, err\n\t}\n\treturn result, nil\n}\n\n`;
    } else {
      endpointsContent += `\treturn c.doRequest(ctx, "${ep.method}", relPath, query, ${Boolean(ep.requestBodySchema || ep.requestBodyProperties) ? 'payload' : 'nil'}, nil)\n}\n\n`;
    }
  }

  files.push({
    name: 'endpoints.go',
    path: 'endpoints.go',
    content: endpointsContent,
    language: 'go',
    sizeBytes: new TextEncoder().encode(endpointsContent).length
  });

  // 4. Generate go.mod
  const goModContent = `module github.com/${opts.author ? opts.author.toLowerCase().replace(/[^a-z0-9]/g, '') : 'apidev'}/${pkgName}

go 1.22
`;

  files.push({
    name: 'go.mod',
    path: 'go.mod',
    content: goModContent,
    language: 'go',
    sizeBytes: new TextEncoder().encode(goModContent).length
  });

  // 5. Generate README.md
  const sampleEp = spec.endpoints[0];
  const sampleMethodName = toPascalCase(sampleEp?.functionName || 'GetItems');

  const readmeContent = `# ${spec.title} - Go SDK

Idiomatic Go client package generated deterministically by SDKForge.

## Installation

\`\`\`bash
go get github.com/${opts.author ? opts.author.toLowerCase().replace(/[^a-z0-9]/g, '') : 'apidev'}/${pkgName}
\`\`\`

## Quickstart

\`\`\`go
package main

import (
	"context"
	"fmt"
	"log"
	"time"

	sdk "github.com/${opts.author ? opts.author.toLowerCase().replace(/[^a-z0-9]/g, '') : 'apidev'}/${pkgName}"
)

func main() {
	client := sdk.NewClient(
		sdk.WithBaseURL("${spec.baseUrl || 'https://api.example.com'}"),
		sdk.WithBearerToken("your_secret_token"),
	)

	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()

	res, err := client.${sampleMethodName}(ctx)
	if err != nil {
		log.Fatalf("API call failed: %v", err)
	}

	fmt.Printf("Success: %+v\\n", res)
}
\`\`\`

## Available Methods (${spec.endpoints.length} Total)

| Method | HTTP | Path |
| :--- | :--- | :--- |
${spec.endpoints.slice(0, 15).map(ep => `| \`${toPascalCase(ep.functionName)}\` | \`${ep.method}\` | \`${ep.path}\` |`).join('\n')}

## License

MIT License
`;

  files.push({
    name: 'README.md',
    path: 'README.md',
    content: readmeContent,
    language: 'markdown',
    sizeBytes: new TextEncoder().encode(readmeContent).length
  });

  // 6. client_test.go
  const testContent = `package ${pkgName}

import (
	"testing"
)

func TestNewClient(t *testing.T) {
	c := NewClient(
		WithBaseURL("${spec.baseUrl || 'https://api.example.com'}"),
		WithBearerToken("test_secret"),
	)

	if c == nil {
		t.Fatal("expected non-nil client")
	}

	if c.token != "test_secret" {
		t.Errorf("expected token test_secret, got %s", c.token)
	}
}
`;

  files.push({
    name: 'client_test.go',
    path: 'client_test.go',
    content: testContent,
    language: 'go',
    sizeBytes: new TextEncoder().encode(testContent).length
  });

  return files;
}
