import { SDKFile, SDKGenOptions, SpecValidationDiagnostic } from '../../types/spec';
import { toCamelCase, toPascalCase, toSnakeCase } from '../parser';
import { apiKeyHeaderName, snakeArg, clientClassNameFor } from './common';
import { safeText, safePackageName, safeVersion, safeAuthor, safeVarName } from '../sanitize';

function mapPythonType(typeStr: string): string {
  if (typeStr.includes('"')) return typeStr.endsWith('[]') ? 'List[str]' : 'str'; // string-literal unions
  if (typeStr === 'string') return 'str';
  if (typeStr === 'number') return 'float';
  if (typeStr === 'integer') return 'int';
  if (typeStr === 'boolean') return 'bool';
  if (typeStr.endsWith('[]')) {
    const item = typeStr.slice(0, -2);
    return `List[${mapPythonType(item)}]`;
  }
  if (typeStr === 'Record<string, any>' || typeStr === 'any') return 'Dict[str, Any]';
  return typeStr; // schema class
}

export function generatePythonSDK(
  spec: SpecValidationDiagnostic,
  opts: SDKGenOptions
): SDKFile[] {
  const files: SDKFile[] = [];

  const pkgName = safeVarName(safePackageName(opts.packageName, 'api_client_sdk').replace(/[^a-z0-9_]/g, '_'), 'api_client_sdk');
  const pkgVersion = safeVersion(opts.version);
  const apiKeyHeader = apiKeyHeaderName(spec);
  const clientClassName = clientClassNameFor(spec);
  const isHttpx = opts.httpClient === 'httpx';
  // Async controllers are generated with httpx.AsyncClient when asyncMode is on
  const isAsync = isHttpx && Boolean(opts.asyncMode);
  const aw = isAsync ? 'await ' : '';
  const asyncKw = isAsync ? 'async ' : '';

  // 1. Generate models.py
  let modelsContent = `"""
${spec.title} - Python Data Models
Auto-generated by SDKForge Engine
"""

from __future__ import annotations

from typing import Optional, List, Dict, Any, Union
from dataclasses import dataclass, field


class APIError(Exception):
    """Raised when an API endpoint returns a non-2xx status code."""
    def __init__(self, message: str, status_code: int = 0, response_data: Any = None):
        super().__init__(message)
        self.status_code = status_code
        self.response_data = response_data

    def __str__(self) -> str:
        return f"[Status {self.status_code}] {super().__str__()}"
\n`;

  for (const schema of spec.schemas) {
    modelsContent += `@dataclass\nclass ${schema.name}:\n`;
    if (schema.description) {
      modelsContent += `    """${safeText(schema.description)}"""\n`;
    }
    if (schema.properties.length === 0) {
      modelsContent += `    pass\n\n`;
      continue;
    }

    // Required fields first, then optional fields with default None
    const reqProps = schema.properties.filter(p => p.required);
    const optProps = schema.properties.filter(p => !p.required);

    for (const p of reqProps) {
      const pyType = mapPythonType(p.type);
      modelsContent += `    ${safeVarName(toSnakeCase(p.name), 'field_')}: ${pyType}\n`;
    }
    for (const p of optProps) {
      const pyType = mapPythonType(p.type);
      modelsContent += `    ${safeVarName(toSnakeCase(p.name), 'field_')}: Optional[${pyType}] = None\n`;
    }
    modelsContent += `\n`;
  }

  files.push({
    name: 'models.py',
    path: `${pkgName}/models.py`,
    content: modelsContent,
    language: 'python',
    sizeBytes: new TextEncoder().encode(modelsContent).length
  });

  // 2. Generate client.py
  let clientContent = `"""
${spec.title} - Main Python Client
Auto-generated by SDKForge Engine
"""

from __future__ import annotations

from typing import Optional, Dict, Any, List, Union
from urllib.parse import urlencode, quote
from .models import ${Array.from(new Set(['APIError', ...spec.schemas.map(sc => sc.name)])).join(', ')}

${isHttpx ? 'import httpx' : 'import requests'}


class ${clientClassName}:
    def __init__(
        self,
        base_url: str = "${spec.baseUrl || 'https://api.example.com'}",
        api_key: Optional[str] = None,
        bearer_token: Optional[str] = None,
        timeout: float = 30.0,
        headers: Optional[Dict[str, str]] = None,
    ):
        self.base_url = base_url.rstrip("/")
        self.api_key = api_key
        self.bearer_token = bearer_token
        self.timeout = timeout
        
        self.default_headers = {
            "Content-Type": "application/json",
            "Accept": "application/json",
            "User-Agent": "${pkgName}/${pkgVersion}"
        }
        if headers:
            self.default_headers.update(headers)

        if self.bearer_token:
            self.default_headers["Authorization"] = f"Bearer {self.bearer_token}"
        elif self.api_key:
            self.default_headers["${apiKeyHeader}"] = self.api_key

        ${isHttpx ? `self._client = httpx.${isAsync ? 'AsyncClient' : 'Client'}(timeout=self.timeout)` : 'self._session = requests.Session()'}

    ${asyncKw}def _request(
        self,
        method: str,
        path: str,
        params: Optional[Dict[str, Any]] = None,
        json_data: Optional[Dict[str, Any]] = None,
        headers: Optional[Dict[str, str]] = None
    ) -> Any:
        url = f"{self.base_url}{path}"
        req_headers = {**self.default_headers, **(headers or {})}

        try:
${isHttpx ? `            response = ${aw}self._client.request(
                method=method,
                url=url,
                params={k: v for k, v in (params or {}).items() if v is not None},
                json=json_data,
                headers=req_headers
            )
            status_code = response.status_code
            if not response.is_success:
                raise APIError(f"HTTP {status_code}: {response.text}", status_code, response.text)
            
            if "application/json" in response.headers.get("content-type", ""):
                return response.json()
            return response.text` : `            response = self._session.request(
                method=method,
                url=url,
                params={k: v for k, v in (params or {}).items() if v is not None},
                json=json_data,
                headers=req_headers,
                timeout=self.timeout
            )
            status_code = response.status_code
            if not response.ok:
                raise APIError(f"HTTP {status_code}: {response.text}", status_code, response.text)
            
            if "application/json" in response.headers.get("content-type", ""):
                return response.json()
            return response.text`}
        except Exception as e:
            if isinstance(e, APIError):
                raise
            raise APIError(f"Request failed: {str(e)}", 0)
`;

  // Methods
  for (const ep of spec.endpoints) {
    const pyMethodName = safeVarName(toSnakeCase(ep.functionName), 'endpoint');
    const pathParams = ep.parameters.filter(p => p.in === 'path');
    const queryParams = ep.parameters.filter(p => p.in === 'query');

    const methodArgs: string[] = ['self'];
    for (const p of pathParams) {
      methodArgs.push(`${snakeArg(p)}: ${mapPythonType(p.type)}`);
    }

    if (ep.requestBodySchema) {
      methodArgs.push(`payload: Union[${ep.requestBodySchema}, Dict[str, Any]]`);
    } else if (ep.requestBodyProperties) {
      methodArgs.push(`payload: Dict[str, Any]`);
    }

    if (queryParams.length > 0) {
      for (const q of queryParams) {
        methodArgs.push(`${snakeArg(q)}: Optional[${mapPythonType(q.type)}] = None`);
      }
    }

    clientContent += `
    ${asyncKw}def ${pyMethodName}(
        ${methodArgs.join(',\n        ')}
    ) -> Any:
        """${safeText(ep.summary)}
        Endpoint: ${ep.method} ${ep.path}
        """
        path = "${ep.path}"
${pathParams.map(p => `        path = path.replace("{${p.name}}", quote(str(${snakeArg(p)}), safe=\"\"))`).join('\n')}

        params = {}
${queryParams.map(q => `        if ${snakeArg(q)} is not None:\n            params["${q.name}"] = ${snakeArg(q)}`).join('\n')}

        return ${aw}self._request(
            method="${ep.method}",
            path=path,
            params=params if params else None,
            json_data=payload if ${Boolean(ep.requestBodySchema || ep.requestBodyProperties)} else None
        )
`;
  }

  // Lifecycle helpers (context manager support) so connections are always released
  const closeTarget = isHttpx ? 'self._client' : 'self._session';
  clientContent += isAsync
    ? `
    async def aclose(self) -> None:
        \"\"\"Close the underlying async HTTP connection pool.\"\"\"
        await ${closeTarget}.aclose()

    async def __aenter__(self) -> "${clientClassName}":
        return self

    async def __aexit__(self, *exc_info: Any) -> None:
        await self.aclose()
`
    : `
    def close(self) -> None:
        \"\"\"Close the underlying HTTP connection pool.\"\"\"
        ${closeTarget}.close()

    def __enter__(self) -> "${clientClassName}":
        return self

    def __exit__(self, *exc_info: Any) -> None:
        self.close()
`;

  files.push({
    name: 'client.py',
    path: `${pkgName}/client.py`,
    content: clientContent,
    language: 'python',
    sizeBytes: new TextEncoder().encode(clientContent).length
  });

  // 3. Generate __init__.py
  const initContent = `"""
${spec.title} Python SDK
"""

from .client import ${clientClassName}
from .models import APIError

__version__ = "${pkgVersion}"
__all__ = ["${clientClassName}", "APIError"]
`;

  files.push({
    name: '__init__.py',
    path: `${pkgName}/__init__.py`,
    content: initContent,
    language: 'python',
    sizeBytes: new TextEncoder().encode(initContent).length
  });

  // 4. Generate pyproject.toml
  const pyprojectContent = `[build-system]
requires = ["setuptools>=61.0"]
build-backend = "setuptools.build_meta"

[project]
name = "${pkgName}"
version = "${pkgVersion}"
description = "${spec.description || `Python SDK for ${spec.title}`}"
readme = "README.md"
requires-python = ">=3.9"
dependencies = [
    "${isHttpx ? 'httpx>=0.27.0' : 'requests>=2.31.0'}",
]

[project.optional-dependencies]
dev = [
    "pytest>=8.0.0",
]
`;

  files.push({
    name: 'pyproject.toml',
    path: 'pyproject.toml',
    content: pyprojectContent,
    language: 'text',
    sizeBytes: new TextEncoder().encode(pyprojectContent).length
  });

  // 5. Generate README.md
  const sampleEp = spec.endpoints[0];
  const sampleArgs = sampleEp
    ? sampleEp.parameters.filter(p => p.in === 'path').map(p => (p.type === 'number' ? '1' : `"sample_${p.name}"`)).join(', ')
    : '';
  const pySampleCall = sampleEp
    ? `result = ${aw}client.${safeVarName(toSnakeCase(sampleEp.functionName), 'endpoint')}(${sampleArgs})`
    : `result = ${aw}client.list_items()`;

  const readmeContent = `# ${spec.title} - Python SDK

${spec.description || 'Production-grade Python client library generated deterministically by SDKForge.'}

## Installation

\`\`\`bash
pip install ${pkgName}
\`\`\`

## Quickstart

\`\`\`python
from ${pkgName} import ${clientClassName}, APIError

client = ${clientClassName}(
    base_url="${spec.baseUrl || 'https://api.example.com'}",
    bearer_token="your_secret_token_here",
)

${isAsync
  ? `import asyncio


async def main():
    try:
        ${pySampleCall}
        print("API Response:", result)
    except APIError as e:
        print(f"API Error ({e.status_code}): {e}")
    finally:
        await client.aclose()


asyncio.run(main())`
  : `try:
    ${pySampleCall}
    print("API Response:", result)
except APIError as e:
    print(f"API Error ({e.status_code}): {e}")`}
\`\`\`

## Endpoint Methods (${spec.endpoints.length} Total)

| Method | HTTP | Path | Description |
| :--- | :--- | :--- | :--- |
${spec.endpoints.slice(0, 15).map(ep => `| \`${toSnakeCase(ep.functionName)}\` | \`${ep.method}\` | \`${ep.path}\` | ${ep.summary} |`).join('\n')}

${spec.endpoints.length > 15 ? `*...and ${spec.endpoints.length - 15} more methods.*\n` : ''}

## Testing

\`\`\`bash
pytest tests/
\`\`\`

## License

MIT © ${new Date().getFullYear()} ${opts.author || 'API Platform Team'}
`;

  files.push({
    name: 'README.md',
    path: 'README.md',
    content: readmeContent,
    language: 'markdown',
    sizeBytes: new TextEncoder().encode(readmeContent).length
  });

  // 6. Generate tests/test_client.py
  const testContent = `"""
Unit tests for ${clientClassName}
"""

import pytest
from ${pkgName} import ${clientClassName}, APIError


def test_client_init():
    client = ${clientClassName}(
        base_url="${spec.baseUrl || 'https://api.example.com'}",
        bearer_token="token_test_123"
    )
    assert client.base_url == "${spec.baseUrl || 'https://api.example.com'}"
    assert "Authorization" in client.default_headers
    assert client.default_headers["Authorization"] == "Bearer token_test_123"


def test_api_error_attributes():
    err = APIError("Not Found", 404, {"error": "Resource missing"})
    assert err.status_code == 404
    assert "Not Found" in str(err)
`;

  files.push({
    name: 'test_client.py',
    path: 'tests/test_client.py',
    content: testContent,
    language: 'python',
    sizeBytes: new TextEncoder().encode(testContent).length
  });

  return files;
}
